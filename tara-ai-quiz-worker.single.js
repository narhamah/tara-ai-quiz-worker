function buildRoutineBlueprint(state) {
  const specs = [
    {
      role_id: "cleanse",
      step_label: "Cleanse",
      types: ["shampoo"],
      focus_concerns: [state.dominant_concern],
      focus_terms: ["scalp", "cleanse", "reset", "roots", "wash"],
      reason_seed: "Chosen to make the cleansing step work for the pattern showing up at the scalp and roots.",
    },
  ];

  if (needsScalpTreatment(state)) {
    specs.push({
      role_id: "treat",
      step_label: "Treat",
      types: ["serum", "concentrate"],
      focus_concerns: [state.dominant_concern, state.secondary_concern].filter(Boolean),
      focus_terms: ["follicle", "density", "hair fall", "scalp support", "targeted"],
      reason_seed: "Chosen as the targeted step to support the scalp environment behind the concern.",
    });
  }

  if (needsFiberRepair(state)) {
    specs.push({
      role_id: state.dominant_concern === "weakness_and_breakage" ? "repair" : "condition",
      step_label: state.dominant_concern === "weakness_and_breakage" ? "Repair" : "Condition",
      types: state.dominant_concern === "weakness_and_breakage" ? ["mask", "conditioner"] : ["conditioner", "mask"],
      focus_concerns: [state.dominant_concern, state.secondary_concern].filter(Boolean),
      focus_terms: ["repair", "strength", "hydration", "softness", "fiber"],
      reason_seed: "Chosen to support the lengths and ends so the routine is not only scalp-correct, but fiber-correct too.",
    });
  }

  if (needsLeaveInSupport(state)) {
    specs.push({
      role_id: "finish",
      step_label: "Finish",
      types: ["leave-in", "mask", "serum"],
      focus_concerns: [state.dominant_concern, state.secondary_concern].filter(Boolean),
      focus_terms: ["finish", "frizz", "softness", "protection", "manageability"],
      reason_seed: "Chosen as the finishing support step when the hair fiber needs extra day-to-day protection.",
    });
  }

  if (specs.length < state.routine_size) {
    const hasTargetedTreat = specs.some((spec) => spec.role_id === "treat");
    const hasFiberStep = specs.some((spec) => ["condition", "repair", "finish"].includes(spec.role_id));
    const shouldAddConditioningStep = hasTargetedTreat && !hasFiberStep;
    specs.push({
      role_id: shouldAddConditioningStep ? "condition" : "support",
      step_label: shouldAddConditioningStep ? "Condition" : "Support",
      types: shouldAddConditioningStep ? ["conditioner", "mask"] : ["conditioner", "mask", "leave-in"],
      focus_concerns: [state.secondary_concern || state.dominant_concern].filter(Boolean),
      focus_terms: shouldAddConditioningStep ? ["softness", "slip", "conditioning", "fiber"] : ["support", "balance", "maintenance"],
      reason_seed: shouldAddConditioningStep
        ? "Chosen to support softness, slip, and fiber comfort so the routine is not only targeted at the scalp."
        : "Chosen to round out the routine so it supports the whole pattern, not just one symptom.",
    });
  }

  while (specs.length < state.routine_size) {
    specs.push({
      role_id: `support_${specs.length}`,
      step_label: "Support",
      types: ["conditioner", "mask", "leave-in", "serum"],
      focus_concerns: [state.dominant_concern, state.secondary_concern].filter(Boolean),
      focus_terms: ["support", "maintenance", "balance"],
      reason_seed: "Chosen to complete the routine around the user's full pattern.",
    });
  }

  return specs.slice(0, state.routine_size);
}

function scoreCatalogProductForRole(product, state, roleSpec, usedCollections) {
  let score = scoreCatalogProductForConsultation(product, state);
  if (roleSpec.types.includes(product.product_type)) {
    score += 40;
  } else if (roleSpec.role_id === "finish" && ["serum", "leave-in", "mask"].includes(product.product_type)) {
    score += 12;
  } else if (roleSpec.role_id === "repair" && ["mask", "conditioner"].includes(product.product_type)) {
    score += 14;
  } else {
    score -= 30;
  }

  const focusCollections = roleSpec.focus_concerns.flatMap((concernId) => getConcernFrameworkMap()[concernId]?.best_collections || []);
  if (focusCollections.includes(product.collection_id)) {
    score += 10;
  }

  const productText = normalizeText(
    [
      product.quiz_pitch,
      ...(product.primary_concerns || []),
      ...(product.secondary_concerns || []),
      ...(product.customer_signals || []),
      ...(product.recommendation_reasons || []),
    ].join(" "),
  );
  for (const term of roleSpec.focus_terms || []) {
    if (productText.includes(normalizeText(term))) {
      score += 4;
    }
  }
  for (const concernId of roleSpec.focus_concerns || []) {
    for (const keyword of CONCERN_KEYWORDS[concernId] || []) {
      if (productText.includes(keyword)) {
        score += 3;
      }
    }
  }

  if (usedCollections.has(product.collection_id)) {
    score += state.secondary_concern ? 1 : 4;
  } else if (state.secondary_concern && usedCollections.size > 0) {
    score += 3;
  }

  return score;
}

function chooseCatalogRoutine(state) {
  const quizProducts = (TARA_QUIZ_KNOWLEDGE.product_catalog || []).filter((product) => product.eligible_for_quiz);
  const blueprint = buildRoutineBlueprint(state);
  const selected = [];
  const usedProductIds = new Set();
  const usedCollections = new Set();

  for (const roleSpec of blueprint) {
    const ranked = [...quizProducts]
      .filter((product) => !usedProductIds.has(product.product_id))
      .sort(
        (left, right) =>
          scoreCatalogProductForRole(right, state, roleSpec, usedCollections) -
          scoreCatalogProductForRole(left, state, roleSpec, usedCollections),
      );
    const best = ranked[0];
    if (!best) continue;
    usedProductIds.add(best.product_id);
    if (best.collection_id) usedCollections.add(best.collection_id);
    selected.push({
      product: best,
      role_id: roleSpec.role_id,
      step_label: roleSpec.step_label,
      reasoning_seed: roleSpec.reason_seed,
      preferred_types: [...(roleSpec.types || [])],
      focus_collections: roleSpec.focus_concerns.flatMap((concernId) => getConcernFrameworkMap()[concernId]?.best_collections || []),
    });
  }

  return selected.slice(0, state.routine_size);
}

function determineHeroRolePriority(state) {
  switch (state.dominant_concern) {
    case "hair_fall_and_thinning":
      return ["treat", "cleanse", "repair", "condition", "finish", "support"];
    case "scalp_buildup_and_oiliness":
      return ["cleanse", "treat", "condition", "repair", "finish", "support"];
    case "dryness_and_dehydration":
      return ["condition", "repair", "finish", "cleanse", "treat", "support"];
    case "weakness_and_breakage":
      return ["repair", "treat", "cleanse", "finish", "condition", "support"];
    default:
      return ["treat", "repair", "cleanse", "condition", "finish", "support"];
  }
}

function scoreIndividualRecommendationSeed(state, hero, steps) {
  const allSteps = [...(hero ? [hero] : []), ...(steps || [])];
  if (!allSteps.length) return 0;

  const roleIds = new Set(allSteps.map((step) => step.role_id));
  const collectionIds = new Set(
    allSteps
      .map((step) => step.catalog_product?.collection_id || step.collection_id || null)
      .filter(Boolean),
  );

  let score = allSteps.length * 28;
  if (roleIds.has("cleanse")) score += 14;
  if (needsScalpTreatment(state) && (roleIds.has("treat") || roleIds.has("cleanse"))) score += 14;
  if (needsFiberRepair(state) && [...roleIds].some((roleId) => ["repair", "condition", "finish", "support"].includes(roleId))) {
    score += 14;
  }
  if (roleIds.has("finish") && needsLeaveInSupport(state)) score += 8;
  if (allSteps.length >= Math.min(state.routine_size, 3)) score += 10;
  if (allSteps.length < Math.min(state.routine_size, 2)) score -= 18;

  if (collectionIds.size === 1) {
    score += 8;
  } else if (collectionIds.size > 1) {
    score += state.secondary_concern ? 10 : 3;
  }

  if (hero && hero.role_id === "treat" && state.dominant_concern === "hair_fall_and_thinning") score += 8;
  if (hero && hero.role_id === "cleanse" && state.dominant_concern === "scalp_buildup_and_oiliness") score += 8;
  if (hero && hero.role_id === "repair" && state.dominant_concern === "weakness_and_breakage") score += 8;
  if (hero && hero.role_id === "condition" && state.dominant_concern === "dryness_and_dehydration") score += 6;

  return score;
}

function buildIndividualRecommendationSeed(state, desiredCatalogSteps, normalizedProducts) {
  const usedAvailableHandles = new Set();
  const mappedSteps = desiredCatalogSteps.map((desiredStep) => {
    const catalogProduct = desiredStep.product;
    const rankedMatches = normalizedProducts
      .map((product) => ({
        product,
        score: scoreAvailableProductForDesiredStep(
          {
            catalog_product: catalogProduct,
            role_id: desiredStep.role_id,
            step_label: desiredStep.step_label,
            preferred_types: desiredStep.preferred_types,
            focus_collections: desiredStep.focus_collections,
          },
          product,
        ),
      }))
      .sort((left, right) => right.score - left.score);
    const preferredMatch =
      rankedMatches.find((item) => item.score > 0 && !usedAvailableHandles.has(item.product.handle)) ||
      rankedMatches.find((item) => item.score > 0) ||
      null;
    const bestMatch = preferredMatch?.product || null;
    const bestScore = preferredMatch?.score ?? -1;
    if (bestMatch?.handle && bestScore > 0) {
      usedAvailableHandles.add(bestMatch.handle);
    }
    return {
      catalog_product: catalogProduct,
      role_id: desiredStep.role_id,
      step_label: desiredStep.step_label,
      reasoning_seed: desiredStep.reasoning_seed,
      available_product: bestScore > 0 ? bestMatch : null,
      match_score: bestScore,
    };
  });

  const routineSteps = mappedSteps
    .filter((item) => item.available_product)
    .map((item) => ({
      handle: item.available_product.handle,
      title: item.available_product.title,
      subtitle: item.available_product.subtitle,
      hero: false,
      role_id: item.role_id,
      step_label: item.step_label,
      reasoning_seed:
        item.available_product.collection_id && item.catalog_product.collection_id === item.available_product.collection_id
          ? (item.catalog_product.recommendation_reasons?.[0] || item.reasoning_seed || item.catalog_product.quiz_pitch)
          : (item.reasoning_seed || item.catalog_product.quiz_pitch),
      catalog_product: item.catalog_product,
      collection_id: item.available_product.collection_id || item.catalog_product.collection_id || null,
    }));

  const dedupedRoutineSteps = [];
  const seenHandles = new Set();
  for (const step of routineSteps) {
    if (!step.handle || seenHandles.has(step.handle)) continue;
    seenHandles.add(step.handle);
    dedupedRoutineSteps.push(step);
  }

  const heroRolePriority = determineHeroRolePriority(state);
  const hero = dedupedRoutineSteps
    .slice()
    .sort(
      (left, right) =>
        heroRolePriority.indexOf(left.role_id) - heroRolePriority.indexOf(right.role_id),
    )[0] || null;

  if (hero) {
    hero.hero = true;
  }

  const steps = dedupedRoutineSteps
    .filter((step) => !hero || step.handle !== hero.handle)
    .slice(0, Math.max(1, state.routine_size - 1));

  const strategyCollections = Array.from(
    new Set(
      [...(hero ? [hero] : []), ...steps]
        .map((step) => step.collection_id || step.catalog_product?.collection_id || null)
        .filter(Boolean),
    ),
  );

  return {
    hero,
    steps,
    strategy: {
      routine_size: state.routine_size,
      collections_used: strategyCollections,
      style: strategyCollections.length > 1 ? "mix_and_match" : "single_collection",
      presentation_mode: "individual",
      score: scoreIndividualRecommendationSeed(state, hero, steps),
    },
  };
}

function summarizeDominantCollection(desiredCatalogSteps) {
  const counts = new Map();
  for (const step of desiredCatalogSteps || []) {
    const collectionId = step.product?.collection_id;
    if (!collectionId) continue;
    counts.set(collectionId, (counts.get(collectionId) || 0) + 1);
  }
  const ranked = [...counts.entries()].sort((left, right) => right[1] - left[1]);
  return {
    dominant_collection_id: ranked[0]?.[0] || null,
    counts,
  };
}

function scoreBundleCandidate(bundleProduct, state, desiredCatalogSteps, individualSeed) {
  let score = 0;
  const bundleText = normalizeText(
    [
      bundleProduct.handle,
      bundleProduct.title,
      bundleProduct.subtitle,
      bundleProduct.collection_id,
      bundleProduct.collection_name,
      ...(bundleProduct.quiz_roles || []),
      ...(bundleProduct.keywords || []),
    ].join(" "),
  );
  const { dominant_collection_id: dominantCollectionId, counts: desiredCollectionCounts } =
    summarizeDominantCollection(desiredCatalogSteps);
  const desiredCollectionIds = new Set([...desiredCollectionCounts.keys()]);
  const dominantCollectionCount = dominantCollectionId ? desiredCollectionCounts.get(dominantCollectionId) || 0 : 0;
  const dominantCoverageRatio = desiredCatalogSteps.length ? dominantCollectionCount / desiredCatalogSteps.length : 0;

  if (bundleProduct.product_type === "bundle") score += 18;
  if (bundleText.includes("complete") || bundleText.includes("full") || bundleText.includes("set") || bundleText.includes("routine")) {
    score += 10;
  }
  if (state.routine_size >= 3) score += 8;
  if (state.routine_size === 2) score -= 4;

  if (bundleProduct.collection_id && bundleProduct.collection_id === dominantCollectionId) {
    score += 32;
  } else if (bundleProduct.collection_id && desiredCollectionIds.has(bundleProduct.collection_id)) {
    score += 18;
  } else if (bundleProduct.collection_id && state.recommended_collections.includes(bundleProduct.collection_id)) {
    score += 12;
  }

  if (desiredCollectionIds.size > 1 && bundleProduct.collection_id === dominantCollectionId) {
    score += 4;
    score -= 10;
  } else if (desiredCollectionIds.size > 1 && bundleProduct.collection_id && !desiredCollectionIds.has(bundleProduct.collection_id)) {
    score -= 22;
  }

  if (dominantCoverageRatio >= 0.9) score += 12;
  else if (dominantCoverageRatio >= 0.75) score += 4;
  else if (dominantCoverageRatio < 0.75) score -= 24;

  for (const desiredStep of desiredCatalogSteps || []) {
    const coverageScore = keywordMatchScore(desiredStep.product, bundleProduct, { bundlePackaging: true });
    score += Math.max(0, Math.min(coverageScore, 20));
  }

  for (const keyword of CONCERN_KEYWORDS[state.dominant_concern] || []) {
    if (bundleText.includes(keyword)) score += 3;
  }
  if (state.secondary_concern) {
    for (const keyword of CONCERN_KEYWORDS[state.secondary_concern] || []) {
      if (bundleText.includes(keyword)) score += 2;
    }
  }

  if (state.dominant_concern === "scalp_buildup_and_oiliness" && !state.secondary_concern && state.routine_size <= 2) {
    score -= 10;
  }

  if ((individualSeed.strategy?.style || "") === "mix_and_match" && desiredCollectionIds.size > 1 && bundleProduct.collection_id === dominantCollectionId) {
    score += 6;
  }

  return score;
}

function chooseBundleRecommendationSeed(state, desiredCatalogSteps, normalizedProducts, individualSeed) {
  const bundleProducts = normalizedProducts.filter((product) => product.product_type === "bundle");
  if (!bundleProducts.length || !individualSeed.hero) return null;

  const rankedBundles = bundleProducts
    .map((bundle) => ({
      bundle,
      score: scoreBundleCandidate(bundle, state, desiredCatalogSteps, individualSeed),
    }))
    .sort((left, right) => right.score - left.score);

  const best = rankedBundles[0];
  if (!best) return null;

  const { dominant_collection_id: dominantCollectionId, counts: desiredCollectionCounts } = summarizeDominantCollection(desiredCatalogSteps);
  const uniqueDesiredCollections = desiredCollectionCounts.size;
  const dominantCollectionCount = dominantCollectionId ? desiredCollectionCounts.get(dominantCollectionId) || 0 : 0;
  const dominantCoverageRatio = desiredCatalogSteps.length ? dominantCollectionCount / desiredCatalogSteps.length : 0;
  const sameCollectionCore = !!best.bundle.collection_id && best.bundle.collection_id === dominantCollectionId;
  const individualScore = individualSeed.strategy?.score || 0;
  const bundleCoversCore = sameCollectionCore && dominantCoverageRatio >= 0.75;
  const shouldPreferBundle =
    best.score >= 72 &&
    (
      best.score >= individualScore + 10 ||
      (bundleCoversCore && individualSeed.strategy?.style === "single_collection" && best.score >= individualScore - 4)
    );

  if (!shouldPreferBundle) return null;

  const supportCandidates = [
    ...(individualSeed.hero ? [individualSeed.hero] : []),
    ...(individualSeed.steps || []),
  ].filter((step) => {
    if (!step?.handle || step.handle === best.bundle.handle) return false;
    if (!best.bundle.collection_id) return true;
    const stepCollectionId = step.collection_id || step.catalog_product?.collection_id || null;
    return stepCollectionId && stepCollectionId !== best.bundle.collection_id;
  });

  const dedupedSupport = [];
  const seenHandles = new Set();
  for (const step of supportCandidates) {
    if (!step.handle || seenHandles.has(step.handle)) continue;
    seenHandles.add(step.handle);
    dedupedSupport.push({
      ...step,
      hero: false,
    });
  }

  const selectedSupport = dedupedSupport.slice(0, Math.max(0, state.routine_size - 1));
  const canStandAlone = uniqueDesiredCollections <= 1 || dominantCoverageRatio >= 0.9;
  if (!selectedSupport.length && !canStandAlone) return null;

  const presentationMode = selectedSupport.length ? "bundle_plus_support" : "bundle";
  const style = selectedSupport.length
    ? "bundle_anchor"
    : "single_collection_bundle";

  return {
    hero: {
      handle: best.bundle.handle,
      title: best.bundle.title,
      subtitle: best.bundle.subtitle,
      hero: true,
      role_id: "bundle",
      step_label: selectedSupport.length ? "Core Routine" : "Complete Routine",
      reasoning_seed: sameCollectionCore
        ? "Chosen because it is the cleanest way to put the core routine in place around the main pattern showing up here."
        : "Chosen because it covers the main routine well and still leaves room for targeted support where you need it.",
      collection_id: best.bundle.collection_id || null,
    },
    steps: selectedSupport,
    strategy: {
      routine_size: state.routine_size,
      collections_used: Array.from(
        new Set(
          [best.bundle.collection_id, ...selectedSupport.map((step) => step.collection_id || step.catalog_product?.collection_id || null)].filter(Boolean),
        ),
      ),
      style,
      presentation_mode: presentationMode,
      bundle_handle: best.bundle.handle,
      score: best.score,
    },
  };
}

function collectSupportedIngredients(catalogProducts, supportedIngredientEntries) {
  const supportedMap = new Map(supportedIngredientEntries.map((item) => [normalizeText(item.display_name), item]));
  const chosen = [];
  for (const entry of catalogProducts) {
    const product = entry.product || entry;
    for (const ingredient of product.hero_ingredients || []) {
      const key = normalizeText(ingredient);
      if (supportedMap.has(key) && !chosen.some((item) => normalizeText(item.name) === key)) {
        chosen.push({ name: ingredient, support: supportedMap.get(key) });
      }
      if (chosen.length >= 3) return chosen;
    }
  }
  return chosen;
}

