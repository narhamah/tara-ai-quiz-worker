async function handleAssessment(body, env) {
  const provider = String(body.provider || "openai").trim().toLowerCase();
  if (provider !== "openai") return errorResponse("This worker is configured for OpenAI quiz flows.", 400, env);
  if (!env.OPENAI_API_KEY) return errorResponse("OPENAI_API_KEY is not configured.", 500, env);

  const sessionId = String(body.session_id || crypto.randomUUID());
  const session = (await loadSession(sessionId, env)) || initSession(sessionId);
  const history = coalesceHistory(session.history, body.conversation_history || [], null);
  if (!history.length) return errorResponse("conversation_history is required.", 400, env);

  const state = buildConsultationState(history);
  const recommendationSeed = mapCatalogRoutineToAvailableProducts(state, body.products || []);
  const input = buildAssessmentInput(state, history, recommendationSeed, body.products || []);
  const vectorStoreIds = getAssessmentVectorStoreIds(env);
  const tools = vectorStoreIds.length
    ? [{ type: "file_search", vector_store_ids: vectorStoreIds, max_num_results: positiveInt(body.max_search_results, 8) }]
    : [];

  let parsed = buildFallbackAssessment(state, recommendationSeed);
  let debug = null;

  try {
    const result = await callOpenAIResponses({
      apiKey: env.OPENAI_API_KEY,
      model: String(body.openai_assessment_model || env.OPENAI_ASSESSMENT_MODEL || "gpt-5.4"),
      instructions: ASSESSMENT_SYSTEM_PROMPT,
      input,
      textFormat: ASSESSMENT_TEXT_FORMAT,
      reasoningEffort: String(body.openai_assessment_effort || env.OPENAI_ASSESSMENT_EFFORT || "high"),
      maxOutputTokens: 8192,
      tools,
    });
    parsed = safeParseJson(result.text, parsed);
    debug = {
      model: body.openai_assessment_model || env.OPENAI_ASSESSMENT_MODEL || "gpt-5.4",
      duration_ms: result.duration_ms,
      usage: result.usage,
      vector_store_ids: vectorStoreIds,
      recommendation_seed: {
        strategy: recommendationSeed.strategy,
        hero: recommendationSeed.hero?.handle || null,
        steps: recommendationSeed.steps.map((step) => step.handle),
      },
    };
  } catch (error) {
    console.error("Assessment generation error:", error);
    debug = {
      error: error.message,
      vector_store_ids: vectorStoreIds,
      recommendation_seed: {
        strategy: recommendationSeed.strategy,
        hero: recommendationSeed.hero?.handle || null,
        steps: recommendationSeed.steps.map((step) => step.handle),
      },
    };
  }

  parsed.recommended_products = mergeRecommendedProducts(recommendationSeed, parsed.recommended_products);
  parsed.ingredient_highlights = normalizeIngredientHighlights(parsed.ingredient_highlights, recommendationSeed.supported_ingredients);

  const klaviyoProperties = {
    ...(parsed.klaviyo_properties || {}),
    concern_level: parsed.concern_level || state.concern_level,
    primary_concern: state.dominant_concern,
    concern_pattern: [state.dominant_concern, state.secondary_concern].filter(Boolean).join(" + "),
    assessment_headline: parsed.assessment_headline,
    recommended_handles: parsed.recommended_products.map((item) => item.handle).join(","),
  };

  session.history = history;
  session.profile = state;
  session.assessment = { ...parsed, klaviyo_properties: klaviyoProperties };
  await saveSession(session, env);

  const responsePayload = { ...parsed, session_id: sessionId };
  delete responsePayload.klaviyo_properties;
  if (body.debug) responsePayload._debug = debug;

  if (body.email && env.KLAVIYO_API_KEY) {
    upsertKlaviyoProfile(body.email, buildQuizProfileProperties(session), env).catch((error) =>
      console.error("Klaviyo assessment profile sync failed:", error),
    );
  }

  return jsonResponse(responsePayload, 200, env);
}

async function handleEmail(body, env, request) {
  const email = String(body.email || "").trim();
  if (!email) return errorResponse("email is required.", 400, env);

  const sessionId = String(body.session_id || crypto.randomUUID());
  const session = (await loadSession(sessionId, env)) || initSession(sessionId);
  const history = coalesceHistory(session.history, body.conversation_history || [], null);
  if (history.length) {
    session.history = history;
    if (!session.profile) session.profile = buildConsultationState(history);
  }

  session.email_capture = {
    email,
    subscribe_marketing: !!body.subscribe_marketing,
    captured_at: new Date().toISOString(),
  };
  await saveSession(session, env);

  if (env.KLAVIYO_API_KEY) {
    await upsertKlaviyoProfile(email, buildQuizProfileProperties(session), env);
    await trackKlaviyoEvent(
      email,
      "Tara Hair Quiz Completed",
      {
        session_id: sessionId,
        dominant_concern: session.profile?.dominant_concern || "",
        concern_level: session.assessment?.concern_level || "",
        recommended_handles: (session.assessment?.recommended_products || []).map((item) => item.handle),
        total_questions: session.history.length,
      },
      env,
    );
    if (body.subscribe_marketing && env.KLAVIYO_LIST_ID) {
      await subscribeKlaviyoProfile(email, env);
    }
  }

  if (env.FB_PIXEL_ID && env.FB_CAPI_ACCESS_TOKEN) {
    await sendFacebookCAPI(email, body.fb || {}, session, env, request);
  }

  return jsonResponse({ success: true, session_id: sessionId }, 200, env);
}

async function upsertKlaviyoProfile(email, properties, env) {
  if (!env.KLAVIYO_API_KEY) return;
  const response = await fetch("https://a.klaviyo.com/api/profile-import/", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Klaviyo-API-Key ${env.KLAVIYO_API_KEY}`,
      revision: env.KLAVIYO_API_REVISION || "2024-10-15",
    },
    body: JSON.stringify({
      data: {
        type: "profile",
        attributes: {
          email,
          properties,
        },
      },
    }),
  });
  if (!response.ok) {
    const raw = await response.text();
    throw new Error(`Klaviyo profile import failed (${response.status}): ${raw}`);
  }
}

