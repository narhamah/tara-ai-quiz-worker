function positiveInt(value, fallback) {
  const parsed = Number(value);
  return Number.isFinite(parsed) && parsed > 0 ? Math.floor(parsed) : fallback;
}

async function handleQuestion(body, env) {
  const provider = String(body.provider || "openai").trim().toLowerCase();
  if (provider !== "openai") return errorResponse("This worker is configured for OpenAI quiz flows.", 400, env);
  if (!env.OPENAI_API_KEY) return errorResponse("OPENAI_API_KEY is not configured.", 500, env);

  const sessionId = String(body.session_id || crypto.randomUUID());
  const session = (await loadSession(sessionId, env)) || initSession(sessionId);
  const history = coalesceHistory(session.history, body.conversation_history || [], body.answer);
  if (!history.length) return errorResponse("conversation_history or answer is required.", 400, env);

  const state = buildConsultationState(history);
  session.history = history;
  session.profile = state;

  if (state.answered_questions >= MAX_QUESTIONS) {
    await saveSession(session, env);
    return jsonResponse({ session_id: sessionId, complete: true }, 200, env);
  }

  const candidateIds = buildCandidateQuestionIds(state);
  const snippets = await retrieveQuestionSnippets(state, history, env, positiveInt(body.max_search_results, 1));
  const input = buildQuestionInput(state, history, candidateIds, snippets);

  let modelResponse = getDefaultQuestionResponse(state, candidateIds, history);
  let debug = null;

  try {
    const result = await callOpenAIResponses({
      apiKey: env.OPENAI_API_KEY,
      model: String(body.openai_question_model || env.OPENAI_QUESTION_MODEL || "gpt-5-nano"),
      instructions: QUESTION_SYSTEM_PROMPT,
      input,
      textFormat: QUESTION_TEXT_FORMAT,
      reasoningEffort: String(body.openai_question_effort || env.OPENAI_QUESTION_EFFORT || "low"),
      tools: [],
    });
    modelResponse = safeParseJson(result.text, modelResponse);
    debug = {
      model: body.openai_question_model || env.OPENAI_QUESTION_MODEL || "gpt-5-nano",
      duration_ms: result.duration_ms,
      usage: result.usage,
      snippets_used: snippets.length,
      candidates: candidateIds,
      state: buildQuestionDebugState(state, candidateIds),
    };
  } catch (error) {
    console.error("Question generation error:", error);
    debug = {
      error: error.message,
      candidates: candidateIds,
      snippets_used: snippets.length,
      state: buildQuestionDebugState(state, candidateIds),
    };
  }

  const chosenQuestionId = candidateIds.includes(modelResponse.question_id) ? modelResponse.question_id : candidateIds[0];
  const chosenQuestion = getQuestionById(chosenQuestionId) || getQuestionById("routine_preference");
  session.last_question = chosenQuestion;
  session.diagnostic_memory = modelResponse.diagnostic_memory || buildDefaultDiagnosticMemory(state, candidateIds);
  await saveSession(session, env);

  const responsePayload = {
    session_id: sessionId,
    question_id: chosenQuestion.id,
    question_text: chosenQuestion.text,
    question_context: String(modelResponse.question_context || "").trim(),
    options: chosenQuestion.options,
    complete: false,
    micro_insight: String(modelResponse.micro_insight || "").trim(),
    bridge_text: String(modelResponse.bridge_text || "").trim(),
  };
  if (body.debug) responsePayload._debug = debug;
  return jsonResponse(responsePayload, 200, env);
}

