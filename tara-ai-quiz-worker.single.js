function turnsEqual(left, right) {
  return (
    String(left?.question_id || "") === String(right?.question_id || "") &&
    String(left?.question || "") === String(right?.question || "") &&
    String(left?.answer || "") === String(right?.answer || "") &&
    String(left?.answer_label || "") === String(right?.answer_label || "")
  );
}

function normalizeHistory(conversationHistory = []) {
  const normalized = [];
  for (const turn of conversationHistory) {
    const parsed = normalizeTurn(turn);
    if (!parsed) continue;
    if (!normalized.length || !turnsEqual(normalized[normalized.length - 1], parsed)) {
      normalized.push(parsed);
    }
  }
  return normalized;
}

function coalesceHistory(sessionHistory, requestHistory, answer) {
  let history = normalizeHistory(sessionHistory || []);
  const incoming = normalizeHistory(requestHistory || []);
  if (incoming.length >= history.length) history = incoming;
  const latestAnswer = normalizeTurn(answer);
  if (latestAnswer && (!history.length || !turnsEqual(history[history.length - 1], latestAnswer))) {
    history = [...history, latestAnswer];
  }
  return history;
}

