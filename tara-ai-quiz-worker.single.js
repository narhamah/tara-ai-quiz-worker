function scoreCatalogProductForConsultation(product, state) {
  let score = 0;
  const collectionPriority = getConcernCollectionPriority(state);
  const collectionIndex = collectionPriority.indexOf(product.collection_id);
  if (collectionIndex >= 0) score += 35 - collectionIndex * 5;
  if (product.product_type === "shampoo") score += 12;
  if (product.product_type === "serum" || product.product_type === "concentrate") {
    score += state.dominant_concern === "hair_fall_and_thinning" ? 18 : 10;
  }
  if (product.product_type === "conditioner" || product.product_type === "mask") {
    score += ["dryness_and_dehydration", "weakness_and_breakage"].includes(state.dominant_concern) ? 15 : 8;
  }
  if (product.product_type === "leave-in") score += state.dominant_concern === "dryness_and_dehydration" ? 10 : 4;

  const productText = normalizeText(
    [
      ...(product.primary_concerns || []),
      ...(product.secondary_concerns || []),
      ...(product.recommendation_reasons || []),
      product.quiz_pitch,
    ].join(" "),
  );
  for (const keyword of CONCERN_KEYWORDS[state.dominant_concern] || []) {
    if (productText.includes(keyword)) score += 4;
  }
  if (state.secondary_concern) {
    for (const keyword of CONCERN_KEYWORDS[state.secondary_concern] || []) {
      if (productText.includes(keyword)) score += 2;
    }
  }
  if (state.dominant_concern === "scalp_buildup_and_oiliness" && product.collection_id === "detox-scalp-hair-revival") {
    score += 18;
  }
  return score;
}

