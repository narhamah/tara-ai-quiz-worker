function inferShopifyProductType(text) {
  const normalized = normalizeText(text);
  if (normalized.includes("set") || normalized.includes("bundle") || normalized.includes("kit") || normalized.includes("routine")) return "bundle";
  if (normalized.includes("serum") || normalized.includes("concentrate")) return "serum";
  if (normalized.includes("leave in") || normalized.includes("leave-in")) return "leave-in";
  if (normalized.includes("mask")) return "mask";
  if (normalized.includes("conditioner")) return "conditioner";
  if (normalized.includes("shampoo") || normalized.includes("cleanse")) return "shampoo";
  return "";
}

function keywordMatchScore(catalogProduct, availableProduct, options = {}) {
  const bundlePackaging = options.bundlePackaging === true;
  const haystack = normalizeText(
    [
      availableProduct.handle,
      availableProduct.title,
      availableProduct.subtitle,
      availableProduct.collection_id,
      availableProduct.collection_name,
      ...(availableProduct.quiz_roles || []),
      ...(availableProduct.keywords || []),
    ].join(" "),
  );
  let score = 0;
  const catalogTokens = [
    catalogProduct.product_id,
    catalogProduct.display_name,
    catalogProduct.short_name,
    catalogProduct.collection_id,
    catalogProduct.collection_name,
    catalogProduct.product_type,
    catalogProduct.routine_role,
    ...(catalogProduct.retrieval_hints || []),
    ...(catalogProduct.hero_ingredients || []),
  ]
    .map((item) => normalizeText(item))
    .filter(Boolean);

  for (const token of catalogTokens) {
    if (haystack.includes(token)) {
      score += token.includes(" ") ? 6 : 3;
    }
  }
  if (availableProduct.collection_id && availableProduct.collection_id === catalogProduct.collection_id) score += 10;
  if (bundlePackaging) {
    if (availableProduct.product_type === "bundle") score += 12;
  } else if (availableProduct.product_type && availableProduct.product_type === catalogProduct.product_type) {
    score += 24;
  } else if (availableProduct.product_type && catalogProduct.product_type) {
    score -= 28;
  }
  if (availableProduct.title && normalizeText(availableProduct.title).includes(normalizeText(catalogProduct.display_name))) score += 12;
  return score;
}

function scoreAvailableProductForDesiredStep(desiredStep, availableProduct) {
  const catalogProduct = desiredStep.catalog_product;
  let score = keywordMatchScore(catalogProduct, availableProduct);
  const preferredTypes = desiredStep.preferred_types || [];
  const availableType = availableProduct.product_type || "";

  if (preferredTypes.includes(availableType)) {
    score += 24;
  } else if (desiredStep.role_id === "condition" && ["conditioner", "mask", "leave-in"].includes(availableType)) {
    score += 18;
  } else if (desiredStep.role_id === "repair" && ["mask", "conditioner", "leave-in"].includes(availableType)) {
    score += 20;
  } else if (desiredStep.role_id === "finish" && ["leave-in", "mask", "serum"].includes(availableType)) {
    score += 18;
  } else if ((desiredStep.role_id || "").startsWith("support") && ["conditioner", "mask", "leave-in", "serum"].includes(availableType)) {
    score += 12;
  } else if (desiredStep.role_id === "treat" && ["serum", "concentrate"].includes(availableType)) {
    score += 20;
  }

  if (availableProduct.collection_id && availableProduct.collection_id === catalogProduct.collection_id) {
    score += 8;
  }
  for (const collectionId of desiredStep.focus_collections || []) {
    if (collectionId && availableProduct.collection_id === collectionId) {
      score += 6;
      break;
    }
  }

  const roleHaystack = normalizeText(
    [
      ...(availableProduct.quiz_roles || []),
      availableProduct.title,
      availableProduct.subtitle,
      ...(availableProduct.keywords || []),
    ].join(" "),
  );
  if (desiredStep.role_id && roleHaystack.includes(normalizeText(desiredStep.role_id))) score += 8;
  if (desiredStep.step_label && roleHaystack.includes(normalizeText(desiredStep.step_label))) score += 6;

  return score;
}

