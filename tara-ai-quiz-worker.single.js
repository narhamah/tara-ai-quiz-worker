async function searchVectorStore({ apiKey, vectorStoreId, query, maxResults, filters }) {
  const response = await fetch(`${OPENAI_VECTOR_STORES_BASE}/${vectorStoreId}/search`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      query,
      max_num_results: maxResults,
      rewrite_query: false,
      ...(filters ? { filters } : {}),
    }),
  });
  if (!response.ok) {
    const raw = await response.text();
    throw new Error(`Vector store search failed (${response.status}): ${raw}`);
  }
  const payload = await response.json();
  return (payload?.data || []).map((item) => ({
    file_id: item?.file_id || "",
    filename: item?.filename || "",
    score: typeof item?.score === "number" ? item.score : 0,
    text: (item?.content || []).map((part) => part?.text || "").filter(Boolean).join("\n").trim(),
  }));
}

async function retrieveQuestionSnippets(state, history, env, maxResults) {
  const apiKey = env.OPENAI_API_KEY;
  const vectorStoreIds = getQuestionVectorStoreIds(env);
  if (!apiKey || !vectorStoreIds.length || history.length < 2) return [];

  const latestAnswer = history[history.length - 1]?.answer_label || history[history.length - 1]?.answer || "";
  const query = [
    `Dominant concern: ${state.dominant_concern}`,
    `Secondary concern: ${state.secondary_concern || "none"}`,
    `Scalp state: ${state.slots.scalp_state || "unknown"}`,
    `Latest answer: ${latestAnswer}`,
    `Biggest gap: ${buildCandidateQuestionIds(state)[0] || "routine_preference"}`,
  ].join("\n");

  const snippets = [];
  for (const vectorStoreId of vectorStoreIds) {
    try {
      const result = await searchVectorStore({
        apiKey,
        vectorStoreId,
        query,
        maxResults,
        filters: null,
      });
      snippets.push(...result);
    } catch (error) {
      console.error("Question vector search error:", error);
    }
  }

  return snippets
    .filter((snippet) => snippet.text)
    .sort((left, right) => right.score - left.score)
    .slice(0, maxResults)
    .map((snippet, index) => ({
      rank: index + 1,
      source: snippet.filename || snippet.file_id,
      relevance_score: snippet.score,
      text: snippet.text,
    }));
}

async function callOpenAIResponses({ apiKey, model, instructions, input, textFormat, reasoningEffort, maxOutputTokens, tools }) {
  const body = {
    model,
    instructions,
    input,
    tools: tools || [],
    store: false,
    truncation: "auto",
  };
  if (reasoningEffort) body.reasoning = { effort: reasoningEffort };
  if (textFormat) body.text = { format: textFormat };
  if (maxOutputTokens) body.max_output_tokens = maxOutputTokens;

  let lastError = null;
  for (let attempt = 0; attempt < 2; attempt += 1) {
    const startedAt = Date.now();
    const response = await fetch(OPENAI_RESPONSES_URL, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify(body),
    });
    const durationMs = Date.now() - startedAt;
    if (!response.ok) {
      const raw = await response.text();
      lastError = new Error(`OpenAI Responses API failed (${response.status}): ${raw}`);
      if (attempt === 0 && [429, 500, 502, 503, 504].includes(response.status)) {
        continue;
      }
      throw lastError;
    }
    const payload = await response.json();
    const text = (payload?.output || [])
      .filter((item) => item.type === "message")
      .flatMap((item) => item.content || [])
      .filter((part) => part.type === "output_text")
      .map((part) => part.text)
      .join("")
      .trim();

    return {
      text,
      duration_ms: durationMs,
      usage: payload?.usage || null,
    };
  }
  throw lastError || new Error("OpenAI Responses API failed.");
}

